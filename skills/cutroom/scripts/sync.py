#!/usr/bin/env python3
"""project.json + edit/words.json → film/data.js (what the film reads) and audio/cues.json (what sfx.py reads).
Run after ANY change to project.json (sfx list, captions, timings) or to the cut.

  python sync.py [--project .]

SFX events in project.json "sfx": {"t": 4.66, "type": "whoosh", "gain": 0.5, "what": "card in"}
Repeats: {"t": 2.3, "to": 2.9, "every": 0.08, "type": "tick", ...} expand to one cue per step.
"""
import json, os, sys

os.chdir(sys.argv[sys.argv.index('--project') + 1] if '--project' in sys.argv else '.')
P = json.load(open('project.json'))
words = json.load(open('edit/words.json')) if os.path.exists('edit/words.json') else []
cues = []
for ev in P.get('sfx', []):
    if 'every' in ev:
        t = ev['t']
        while t < ev['to'] - 1e-9:
            cues.append({**ev, 't': round(t, 4)}); t += ev['every']
    else:
        cues.append(dict(ev))
cues = sorted([c for c in cues if 0 <= c['t'] < P.get('duration', 1e9)], key=lambda c: c['t'])
for i, c in enumerate(cues):
    c.pop('every', None); c.pop('to', None); c.setdefault('gain', 0.6); c.setdefault('seed', 1000 + i * 37)
os.makedirs('film', exist_ok=True); os.makedirs('audio', exist_ok=True)
json.dump({'sr': 48000, 'duration': P.get('duration', 10), 'cues': cues}, open('audio/cues.json', 'w'), indent=1)
open('film/data.js', 'w').write('// GENERATED by scripts/sync.py — edit project.json instead\n'
                                f'window.PROJECT = {json.dumps(P)};\nwindow.WORDS = {json.dumps(words)};\nwindow.SFX = {json.dumps(cues)};\n')
print(f"film/data.js written · {len(words)} words · {len(cues)} sfx cues · {P.get('duration')} s")
